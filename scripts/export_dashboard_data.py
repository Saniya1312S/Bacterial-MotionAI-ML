"""
Export project data and model predictions to JSON for the static dashboard.

Reads from: data/, results/, models/, src/
Writes to: site/data/, site/images/

This script is deterministic and safe to rerun. It does NOT modify the dataset,
trained model, or existing results.  It only reads them.

Run:  python scripts/export_dashboard_data.py
"""
import os, sys, json, warnings, shutil
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
warnings.filterwarnings("ignore")          # suppress sklearn version warning

import numpy as np
import pandas as pd
from sklearn.metrics import confusion_matrix

from src.data import load_dataset, split_data, RESULTS_DIR, IMAGES_DIR
from src.features import FEATURE_COLS, extract_features
from src.simulation import simulate_bacterium, CHEMICAL_LABELS
from src.inference import load_best_model, predict_trajectory
from src.models import CLASS_NAMES

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SITE_DATA = os.path.join(ROOT, "site", "data")
SITE_IMAGES = os.path.join(ROOT, "site", "images")

# ─── 1. overview.json ─────────────────────────────────────────────────────────
def export_overview():
    df = load_dataset()
    feature_descriptions = {
        "mean_speed":        "Average instantaneous speed (µm/s)",
        "std_speed":         "Speed standard deviation",
        "cv_speed":          "Coefficient of variation of speed",
        "straightness":      "Net displacement / total path length",
        "mean_turn_angle":   "Mean absolute change of direction per step",
        "turn_bias":         "Mean signed turn angle (>0 = left bias)",
        "persistence_1s":    "Directional autocorrelation at 1-second lag",
        "reorient_count":    "Number of large direction changes (>60°) away from walls",
        "mean_alignment":    "Mean |cos θ|  — 1 means swimming parallel to walls",
        "near_wall_frac":    "Fraction of time within 15% of a wall",
        "wall_contact_frac": "Fraction of time within 0.5 µm of a wall",
    }
    overview = {
        "provenance": "Synthetic — generated by src/simulation.py (run-and-tumble model)",
        "rows": int(len(df)),
        "feature_count": len(FEATURE_COLS),
        "features": FEATURE_COLS,
        "feature_descriptions": feature_descriptions,
        "classes": CLASS_NAMES,
        "class_counts": {k: int(v) for k, v in df["chemical"].value_counts().items()},
        "channel_widths": sorted(int(w) for w in df["channel_width"].unique()),
        "hydro_settings": ["off", "on"],
        "samples_per_combo": 50,
        "split": "80/20 stratified, random_state=42",
        "feature_stats": {},
    }
    for col in FEATURE_COLS:
        overview["feature_stats"][col] = {
            "mean": round(float(df[col].mean()), 4),
            "std":  round(float(df[col].std()),  4),
            "min":  round(float(df[col].min()),  4),
            "max":  round(float(df[col].max()),  4),
            "q25":  round(float(df[col].quantile(0.25)), 4),
            "q75":  round(float(df[col].quantile(0.75)), 4),
        }
    # Per-class means for the most important features
    overview["class_feature_means"] = {}
    for chem in CLASS_NAMES:
        sub = df[df["chemical"] == chem]
        overview["class_feature_means"][chem] = {
            col: round(float(sub[col].mean()), 4) for col in FEATURE_COLS
        }
    return overview


# ─── 2. model_metrics.json ────────────────────────────────────────────────────
def export_model_metrics():
    test_df = pd.read_csv(os.path.join(RESULTS_DIR, "test_results.csv"))
    cv_df   = pd.read_csv(os.path.join(RESULTS_DIR, "cv_results.csv"))
    base_df = pd.read_csv(os.path.join(RESULTS_DIR, "baselines.csv"))
    best    = json.load(open(os.path.join(RESULTS_DIR, "best_model.json")))

    models = []
    for _, r in test_df.iterrows():
        cv_row = cv_df[cv_df["model"] == r["model"]].iloc[0]
        models.append({
            "name":           r["model"],
            "train_acc":      round(float(r["train_acc"]), 4),
            "test_acc":       round(float(r["test_acc"]), 4),
            "test_acc_ci":    [round(float(r["test_acc_ci_low"]), 4),
                               round(float(r["test_acc_ci_high"]), 4)],
            "test_macro_f1":  round(float(r["test_macro_f1"]), 4),
            "test_f1_ci":     [round(float(r["test_f1_ci_low"]), 4),
                               round(float(r["test_f1_ci_high"]), 4)],
            "roc_auc":        round(float(r["roc_auc_macro"]), 4),
            "cv_macro_f1":    round(float(r["cv_macro_f1"]), 4),
            "cv_std":         round(float(cv_row["cv_std"]), 4),
            "train_test_gap": round(float(r["train_test_gap"]), 4),
            "best_params":    str(cv_row["best_params"]),
        })

    baselines = [
        {"name": str(r["baseline"]),
         "accuracy":  round(float(r["accuracy"]), 4),
         "macro_f1":  round(float(r["macro_f1"]), 4)}
        for _, r in base_df.iterrows()
    ]

    return {
        "best_model": best,
        "models": models,
        "baselines": baselines,
        "evaluation_method": (
            "Test set (480 samples) used once after all tuning. "
            "95% bootstrap CI computed from 1,000 resamples of test predictions."
        ),
        "cv_method": (
            "5-fold stratified CV with GridSearchCV, scored by macro-F1, "
            "on the training set (1,920 samples) only."
        ),
    }


# ─── 3. class_metrics.json ────────────────────────────────────────────────────
def export_class_metrics():
    """Parse per-class metrics from results.md AND recompute confusion matrix
    from the existing model on the existing test split (deterministic)."""
    # Per-class precision/recall/F1
    per_class = []
    with open(os.path.join(RESULTS_DIR, "results.md"), encoding="utf-8") as f:
        in_table = False
        for line in f:
            if "Per-class" in line:
                in_table = True
                continue
            if in_table and line.startswith("|") and not line.startswith("|:") and "Class" not in line:
                parts = [p.strip() for p in line.strip().strip("|").split("|")]
                if len(parts) >= 4:
                    per_class.append({
                        "class":     parts[0].strip(),
                        "precision": float(parts[1]),
                        "recall":    float(parts[2]),
                        "f1":        float(parts[3]),
                    })

    # Confusion matrix from existing model + existing test split
    model = load_best_model()
    df = load_dataset()
    _, X_test, _, y_test, _ = split_data(df)
    y_pred = model.predict(X_test)
    cm = confusion_matrix(y_test, y_pred, labels=CLASS_NAMES)

    return {
        "model": "Random Forest",
        "per_class": per_class,
        "confusion_matrix": {
            "labels": CLASS_NAMES,
            "matrix": cm.tolist(),
            "method": "Computed from existing best_model.joblib on the 80/20 test split (deterministic).",
        },
    }


# ─── 4. error_analysis.json ───────────────────────────────────────────────────
def export_error_analysis():
    ea_df = pd.read_csv(os.path.join(RESULTS_DIR, "error_analysis.csv"))
    width_groups = []
    hydro_groups = []
    for _, r in ea_df.iterrows():
        entry = {"group": str(r["group"]), "accuracy": round(float(r["accuracy"]), 4)}
        if "width" in r["group"]:
            width_groups.append(entry)
        else:
            hydro_groups.append(entry)
    return {
        "model": "Random Forest",
        "by_width": width_groups,
        "by_hydro": hydro_groups,
    }


# ─── 5. trajectories.json ─────────────────────────────────────────────────────
def export_trajectories():
    """Pre-compute trajectories with the real saved model's predictions."""
    model = load_best_model()
    WIDTHS = [10, 30, 50, 100]             # representative subset for browser
    SEEDS_PER = 5
    DOWNSAMPLE = 10                        # 601 → 61 points per trajectory

    trajectories = []
    total = len(CHEMICAL_LABELS) * len(WIDTHS) * 2 * SEEDS_PER
    done = 0
    for chem in CHEMICAL_LABELS:
        for W in WIDTHS:
            for hydro in [False, True]:
                for si in range(SEEDS_PER):
                    seed = 5000 + si       # distinct from training seeds (0-2399)
                    xs, ys, _ = simulate_bacterium(W, hydro, chem, seed=seed)
                    pred, probs, feats = predict_trajectory(model, xs, ys, W)

                    # Offset x to start at 0 for cleaner display
                    x0 = float(xs[0])
                    xs_ds = [round(float(x) - x0, 2) for x in xs[::DOWNSAMPLE]]
                    ys_ds = [round(float(y), 2) for y in ys[::DOWNSAMPLE]]

                    trajectories.append({
                        "chemical":      chem,
                        "channel_width": int(W),
                        "hydro":         bool(hydro),
                        "seed":          int(seed),
                        "seed_index":    si,
                        "xs": xs_ds,
                        "ys": ys_ds,
                        "features":      {k: round(float(v), 4) for k, v in feats.items()},
                        "prediction":    str(pred),
                        "probabilities": {str(k): float(v) for k, v in probs.items()},
                        "correct":       bool(pred == chem),
                    })
                    done += 1
        print(f"  {chem}: {done}/{total}")

    accuracy = sum(1 for t in trajectories if t["correct"]) / len(trajectories)
    return {
        "label": "Pre-computed real simulator trajectories with the trained model's actual predictions",
        "explanation": (
            "Trajectories were generated by the Python simulator (src/simulation.py) "
            "and classified by the saved Random Forest model (models/best_model.joblib). "
            "The static dashboard displays precomputed results; it does not execute Python. "
            "Changing a control selects a different precomputed example."
        ),
        "downsample_factor": DOWNSAMPLE,
        "original_steps": 601,
        "displayed_points": len(trajectories[0]["xs"]),
        "available_widths": WIDTHS,
        "available_chemicals": CHEMICAL_LABELS,
        "demo_accuracy": round(accuracy, 4),
        "total_trajectories": len(trajectories),
        "trajectories": trajectories,
    }


# ─── Copy evaluation images ───────────────────────────────────────────────────
def copy_images():
    os.makedirs(SITE_IMAGES, exist_ok=True)
    for fname in sorted(os.listdir(IMAGES_DIR)):
        if fname.endswith(".png"):
            shutil.copy2(os.path.join(IMAGES_DIR, fname), SITE_IMAGES)
            sz = os.path.getsize(os.path.join(SITE_IMAGES, fname)) / 1024
            print(f"  Copied {fname} ({sz:.1f} KB)")


# ─── Main ─────────────────────────────────────────────────────────────────────
def main():
    os.makedirs(SITE_DATA, exist_ok=True)

    print("1/6  Exporting overview …")
    _write(export_overview(), "overview.json")

    print("2/6  Exporting model metrics …")
    _write(export_model_metrics(), "model_metrics.json")

    print("3/6  Exporting class metrics + confusion matrix …")
    _write(export_class_metrics(), "class_metrics.json")

    print("4/6  Exporting error analysis …")
    _write(export_error_analysis(), "error_analysis.json")

    print("5/6  Generating trajectories (this takes a moment) …")
    _write(export_trajectories(), "trajectories.json", indent=None)

    print("6/6  Copying evaluation images …")
    copy_images()

    print("\nDone! Dashboard data exported:")
    for f in sorted(os.listdir(SITE_DATA)):
        sz = os.path.getsize(os.path.join(SITE_DATA, f)) / 1024
        print(f"   site/data/{f:30s} {sz:8.1f} KB")
    for f in sorted(os.listdir(SITE_IMAGES)):
        sz = os.path.getsize(os.path.join(SITE_IMAGES, f)) / 1024
        print(f"   site/images/{f:28s} {sz:8.1f} KB")


def _write(obj, name, indent=2):
    path = os.path.join(SITE_DATA, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=indent, ensure_ascii=False)


if __name__ == "__main__":
    main()
